"""Build research/coverage-audit.md from perspectives.md and concerns-v1.md.

Reverse-indexes each concern's Trail so every perspective entry shows which
concerns it reached, and flags entries that reached none.

Limit: "reached" means the entry ID is cited on a concern's trail. The script
cannot check that the citation is faithful (that the concern really carries
what the entry says). Fidelity is checked by human and model review.

The balance view also reads sources.md, so that it can show which perspectives
on a concern rest on a source read in full (access F or A) and which rest only
on search summaries or background knowledge (S or K). Entries tagged
"[strand]" in perspectives.md are listed but never counted as a perspective.
"""
import re
import sys
from collections import defaultdict
from pathlib import Path

root = Path(sys.argv[1] if len(sys.argv) > 1 else "research")
persp = (root / "perspectives.md").read_text()
concerns = (root / "concerns-v1.md").read_text()
access = dict(re.findall(r"^\| (S\d+) \|.*?\| ([FASK])\b[^|]*\| [^|]*\|$",
                         (root / "sources.md").read_text(), re.M))

entries = {}  # id -> (section, text)
entry_src = {}  # id -> [source ids]
section = None
for line in persp.splitlines():
    m = re.match(r"^## (\w+) — (.+)", line)
    if m:
        section = f"{m.group(1)} — {m.group(2)}"
    m = re.match(r"^\| ((?:VOT|CON|CL|PRO|ECM|ECI)-\d+) \| ([^|]+)\|", line)
    if m:
        entries[m.group(1)] = (section, m.group(2).strip())
        entry_src[m.group(1)] = re.findall(r"S\d+", line.split("|")[-2])

part_a = concerns.split("## Part A")[1].split("## Part B")[0]
part_b = concerns.split("## Part B")[1].split("## Part C")[0]
reached = defaultdict(list)
names = {}
for line in part_a.splitlines():
    m = re.match(r"^\| (C\d+) \| ([^|]+)\|.*\| ([^|]*) \| (ok|gap|wording-test) \|$", line)
    if m:
        cid, name, trail = m.group(1), m.group(2).strip(), m.group(3)
        names[cid] = name
        for pid in re.findall(r"(?:VOT|CON|CL|PRO|ECM|ECI)-\d+", trail):
            reached[pid].append(cid)
for line in part_b.splitlines():
    m = re.match(r"^\| (Q\d+) \|.*\| ([^|]*) \|$", line)
    if m:
        for pid in re.findall(r"(?:VOT|CON|CL|PRO|ECM|ECI)-\d+", m.group(2)):
            reached[pid].append(m.group(1))

unknown = sorted(set(reached) - set(entries))
out = ["# Coverage Audit (generated)", "",
       "Generated by `tools/coverage_audit.py`. Do not edit by hand.", "",
       "Shows, for every perspective entry, which concerns (C) or analysis questions (Q) it reached. "
       "**Reached means cited, not verified faithful**; see `bias-review.md` §6. "
       "An entry that reached nothing means that perspective's concern was silently dropped. "
       "Every drop must instead appear in the Excluded log of `concerns-v1.md`.", ""]
summary = defaultdict(lambda: [0, 0])
body = []
cur = None
for pid, (sec, text) in entries.items():
    if sec != cur:
        cur = sec
        body += ["", f"## {sec}", "", "| Entry | Concern | Reached |", "|---|---|---|"]
    hits = reached.get(pid, [])
    summary[sec.split(" — ")[0]][0] += 1
    if hits:
        summary[sec.split(" — ")[0]][1] += 1
    cell = ", ".join(hits) if hits else "**NONE**"
    body.append(f"| {pid} | {text} | {cell} |")
out += ["## Summary", "", "| Perspective | Entries | Reached ≥1 concern/question |", "|---|---|---|"]
for k, (n, r) in summary.items():
    out.append(f"| {k} | {n} | {r} ({100*r//n}%) |")
out += ["", f"Concerns in Part A: {len(names)}"]
if unknown:
    out += ["", f"**Trail cites unknown entry IDs:** {', '.join(unknown)}"]
out += body
(root / "coverage-audit.md").write_text("\n".join(out) + "\n")
print("\n".join(out[:20]))
missing = [p for p in entries if p not in reached]
print("UNREACHED:", missing)

# Balance view: which perspectives each concern draws on.
VOICES = ("CON", "CL", "PRO")
strand = {pid for pid, (_, text) in entries.items() if "[strand]" in text}
full = {pid for pid, srcs in entry_src.items() if any(access.get(s) in ("F", "A") for s in srcs)}
by_concern = defaultdict(set)   # counted perspectives
caveats = defaultdict(list)
fullread = defaultdict(set)
for pid, cids in reached.items():
    kind = pid.split("-")[0]
    for cid in cids:
        if not cid.startswith("C") or kind not in VOICES:
            continue
        if pid in strand:
            caveats[cid].append(f"{pid} is a [strand], not counted")
            continue
        by_concern[cid].add(kind)
        if pid in full:
            fullread[cid].add(kind)
single = sorted((c for c in names if len(by_concern[c]) <= 1), key=lambda c: int(c[1:]))
lines = ["", "## Balance: concerns drawn from a single perspective", "",
         "Concerns whose trail cites at most one voter perspective (CON, CL, PRO). Polling (VOT) and economist lenses (ECM, ECI) are not counted, "
         "and neither are entries tagged [strand] (a minority position within a perspective). "
         "Not wrong in itself, since paired concerns are often one-sided by design, but each needs "
         "a check that the wording would read as fair to the other perspectives.", "",
         "| Concern | Name | Perspectives in trail | Caveat |", "|---|---|---|---|"]
for cid in single:
    lines.append(f"| {cid} | {names[cid]} | {', '.join(sorted(by_concern[cid])) or '(none: mirror or gap)'} | {'; '.join(caveats[cid])} |")
lines += ["", "## Source depth: perspectives backed by a full read", "",
          "For each concern, the perspectives on its trail, and which of them cite at least one source read in full (access F or A in `sources.md`). "
          "A perspective backed only by S or K sources does not count toward freezing (bias review §8).", "",
          "| Concern | Name | Perspectives | Backed by a full read |", "|---|---|---|---|"]
for cid in sorted(names, key=lambda c: int(c[1:])):
    lines.append(f"| {cid} | {names[cid]} | {', '.join(sorted(by_concern[cid])) or '—'} | {', '.join(sorted(fullread[cid])) or '**none**'} |")
n_ok = sum(1 for c in names if len(fullread[c]) >= 2)
lines += ["", f"Concerns with two or more perspectives backed by a full read: {n_ok} of {len(names)}."]
with open(root / "coverage-audit.md", "a") as f:
    f.write("\n".join(lines) + "\n")
print("access levels parsed:", len(access), "strand:", sorted(strand))
