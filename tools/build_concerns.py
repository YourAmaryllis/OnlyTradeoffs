"""Build concerns/v1-draft.yaml from research/concerns-v1.md.

The markdown file stays the single source of truth; this file is generated
and never edited by hand. It holds what the evaluating models receive:
Part A (concerns), Part B (analysis questions), Part C (text-quality flags).

Dropped on purpose, because they must never reach a model:
  - Trail (perspective entry IDs: these carry perspective labels)
  - Status (ok / gap / wording-test)
  - all logs
Kept for the site, but not rendered into prompts: domain.

Usage: python3 tools/build_concerns.py [research/concerns-v1.md] [concerns/v1-draft.yaml]
"""
import hashlib
import re
import sys
from pathlib import Path

import yaml

src = Path(sys.argv[1] if len(sys.argv) > 1 else "research/concerns-v1.md")
out = Path(sys.argv[2] if len(sys.argv) > 2 else "concerns/v1-draft.yaml")
text = src.read_text()

revisions = [int(n) for n in re.findall(r"\*\*Revision (\d+) \(", text)]

part_a = text.split("## Part A")[1].split("## Part B")[0]
part_b = text.split("## Part B")[1].split("## Part C")[0]
part_c = text.split("## Part C")[1].split("\n---")[0]

LABEL_IDS = re.compile(r"\b(?:VOT|CON|CL|PRO|ECM|ECI)-\d+\b")


def cells(line):
    return [c.strip() for c in line.strip().strip("|").split("|")]


def ids(cell):
    return re.findall(r"C\d+", cell)


concerns, domain, status = [], None, {}
for line in part_a.splitlines():
    if line.startswith("### "):
        domain = line[4:].strip()
        continue
    if not re.match(r"^\| C\d+ \|", line):
        continue
    cid, name, axis, adv, check, _trail, st = cells(line)
    if "⇄" in name:
        sys.exit(f"{cid}: directional (⇄) concerns were retired in revision 4; give it an 'advances when' direction")
    mirror = re.search(r"⇆\s*(C\d+)", check)
    mirror = mirror.group(1) if mirror else None
    c = {
        "id": cid,
        "domain": domain,
        "name": name,
        "axis": axis,
        "advances_when": adv,
        "mirror": mirror,
        "check_against": [x for x in ids(check) if x != mirror],
    }
    concerns.append(c)
    status[cid] = st

questions = [{"id": q, "text": re.sub(r"\*\*", "", t)}
             for q, t, _ in (cells(l) for l in part_b.splitlines() if re.match(r"^\| Q\d+ \|", l))]
flags = [{"id": f, "text": t}
         for f, t in (cells(l) for l in part_c.splitlines() if re.match(r"^\| F\d+ \|", l))]

# Integrity checks: fail loudly rather than ship a broken list.
by_id = {c["id"]: c for c in concerns}
errors = []
for c in concerns:
    m = c["mirror"]
    if m and (m not in by_id or by_id[m]["mirror"] != c["id"]):
        errors.append(f"{c['id']}: mirror {m} is not reciprocal")
    for x in c["check_against"]:
        if x not in by_id:
            errors.append(f"{c['id']}: check_against unknown {x}")
    if not c["advances_when"] or c["advances_when"].startswith("—"):
        errors.append(f"{c['id']}: no advances_when")
dump = yaml.safe_dump({"concerns": concerns, "questions": questions, "flags": flags}, allow_unicode=True)
if LABEL_IDS.search(dump):
    errors.append("perspective entry IDs leaked into model input: " + ", ".join(sorted(set(LABEL_IDS.findall(dump)))))
if errors:
    sys.exit("build_concerns: " + "; ".join(errors))

unfrozen = sorted((c for c, s in status.items() if s != "ok"), key=lambda c: int(c[1:]))
doc = {
    "version": f"1-draft.r{max(revisions) if revisions else 0}",
    "frozen": False,
    "generated_from": str(src),
    "source_sha256": hashlib.sha256(text.encode()).hexdigest(),
    "not_frozen_because": f"{len(unfrozen)} concerns are gap or wording-test: {', '.join(unfrozen)}",
    "concerns": concerns,
    "questions": questions,
    "flags": flags,
}
out.parent.mkdir(parents=True, exist_ok=True)
header = ("# GENERATED by tools/build_concerns.py from research/concerns-v1.md. Do not edit by hand.\n"
          "# This is the concern list the evaluating models receive. It contains no perspective labels.\n")
out.write_text(header + yaml.safe_dump(doc, allow_unicode=True, sort_keys=False, width=120))
print(f"{out}: {doc['version']}, {len(concerns)} concerns, {len(questions)} questions, {len(flags)} flags; "
      f"{sum(bool(c['mirror']) for c in concerns)//2} mirror pairs")
